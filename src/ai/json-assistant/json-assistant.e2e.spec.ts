import { expect, test } from '@playwright/test';

test('demo acknowledgement, sample output and local validation without sending payloads', async ({
  page
}) => {
  await page.goto('/json-assistant');
  await expect(
    page.getByRole('heading', { name: 'JSON Assistant Demo' })
  ).toBeVisible();
  await page.waitForLoadState('networkidle');
  const requests: { url: string; method: string; body: string | null }[] = [];
  page.on('request', (request) =>
    requests.push({
      url: request.url(),
      method: request.method(),
      body: request.postData()
    })
  );
  await expect(
    page.getByRole('button', { name: 'Show sample explanation' })
  ).toBeDisabled();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Show sample explanation' }).click();
  await expect(
    page.getByText('Authored sample result - not generated by Claude')
  ).toBeVisible();
  await page.getByRole('button', { name: 'Try demo error' }).click();
  await expect(page.getByText(/Simulated demo error/)).toBeVisible();
  await page
    .getByLabel('JSON input', { exact: true })
    .fill('{"local_only":true}');
  await page
    .getByRole('button', { name: 'Infer candidate schema locally' })
    .click();
  await page.getByRole('button', { name: 'Validate JSON locally' }).click();
  await expect(page.getByText(/Input matches the supported/)).toBeVisible();
  await expect(page.getByRole('checkbox')).not.toBeChecked();
  // Scrolling can load the existing site's "back to top" Iconify resource.
  const inputRequests = requests.filter(
    (request) =>
      !(
        request.method === 'GET' &&
        request.body === null &&
        request.url === 'https://api.iconify.design/mdi.json?icons=arrow-up'
      )
  );
  expect(inputRequests).toEqual([]);
  expect(JSON.stringify(requests)).not.toContain('local_only');
});
