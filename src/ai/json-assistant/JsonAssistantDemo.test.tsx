import { fireEvent, render, screen, waitFor } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';
import JsonAssistantDemo from './JsonAssistantDemo';
import { sampleProvider, type AssistantResult } from './provider';

// MUI cancels its initial -1 frame sentinel. Browsers ignore it, but happy-dom
// 12 passes it to Node 20 clearImmediate, which throws. Keep real frame
// cancellation and emulate only the browser's no-op for that invalid sentinel.
const cancelFrame = globalThis.cancelAnimationFrame;
beforeAll(() => {
  vi.stubGlobal('cancelAnimationFrame', (handle: number) => {
    if (handle !== -1) cancelFrame(handle);
  });
});
afterAll(() => {
  vi.unstubAllGlobals();
});

const mount = () =>
  render(
    <MemoryRouter>
      <JsonAssistantDemo />
    </MemoryRouter>
  );
const consent = () => fireEvent.click(screen.getByRole('checkbox'));
describe('local demo interactions', () => {
  it('requires acknowledgement, labels authored results and exposes recoverable sample errors', async () => {
    mount();
    expect(
      screen.getByRole('button', { name: 'Show sample explanation' })
    ).toBeDisabled();
    consent();
    fireEvent.click(
      screen.getByRole('button', { name: 'Show sample explanation' })
    );
    await screen.findByText('Authored sample result — not generated by Claude');
    fireEvent.click(screen.getByRole('button', { name: 'Try demo error' }));
    await screen.findByText(/Simulated demo error/);
    fireEvent.click(screen.getByRole('button', { name: 'Load Event list' }));
    expect(screen.getByRole('checkbox')).not.toBeChecked();
    expect(screen.queryByText(/Simulated demo error/)).toBeNull();
  });
  it('handles arbitrary JSON locally and refuses unsupported schema keywords', async () => {
    mount();
    fireEvent.change(screen.getByLabelText('JSON input'), {
      target: { value: '{"custom":true}' }
    });
    fireEvent.click(
      screen.getByRole('button', { name: 'Infer candidate schema locally' })
    );
    fireEvent.click(
      screen.getByRole('button', { name: 'Validate JSON locally' })
    );
    expect(screen.getByText(/Input matches/)).toBeVisible();
    fireEvent.change(screen.getByLabelText('Candidate schema'), {
      target: { value: '{"format":"email"}' }
    });
    fireEvent.click(
      screen.getByRole('button', { name: 'Validate JSON locally' })
    );
    expect(screen.getByText(/unsupported keyword/)).toBeVisible();
    consent();
    fireEvent.click(
      screen.getByRole('button', { name: 'Show sample explanation' })
    );
    await screen.findByText(/No sample explanation matches/);
  });
  it('shows loading and discards a result when the input changes before completion', async () => {
    let finish!: (result: AssistantResult) => void;
    const spy = vi.spyOn(sampleProvider, 'explain').mockImplementation(
      () =>
        new Promise((resolve) => {
          finish = resolve;
        })
    );
    try {
      mount();
      consent();
      fireEvent.click(
        screen.getByRole('button', { name: 'Show sample explanation' })
      );
      expect(
        screen.getByText('Preparing the local sample result…')
      ).toBeVisible();
      const signal = spy.mock.calls[0][0].signal;
      fireEvent.click(screen.getByRole('button', { name: 'Clear input' }));
      expect(signal?.aborted).toBe(true);
      finish({
        source: 'authored-sample',
        explanation: 'Stale result',
        suggestion: 'Stale'
      });
      await waitFor(() =>
        expect(
          screen.queryByText('Preparing the local sample result…')
        ).toBeNull()
      );
      expect(screen.queryByText('Stale result')).toBeNull();
    } finally {
      spy.mockRestore();
    }
  });
});
