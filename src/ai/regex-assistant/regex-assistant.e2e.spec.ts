import { expect, test } from '@playwright/test';

test('authored suggestions, consent, custom matches and stale-output clearing', async ({
  page
}) => {
  await page.goto('/regex-assistant');
  await expect(
    page.getByRole('heading', { name: 'Regex Assistant Demo', exact: true })
  ).toBeVisible();
  await page.waitForLoadState('networkidle');
  const uploads: string[] = [];
  const requests: string[] = [];
  page.on('request', (request) => {
    requests.push(request.url() + (request.postData() ?? ''));
    if (request.postData() || !['GET', 'HEAD'].includes(request.method()))
      uploads.push(request.url());
  });
  await expect(
    page.getByRole('button', { name: 'Test regex locally' })
  ).toBeDisabled();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Show sample explanation' }).click();
  await expect(
    page.getByRole('heading', {
      name: 'Authored sample explanation - not generated by Claude'
    })
  ).toBeVisible();
  await page.getByRole('button', { name: 'Test regex locally' }).click();
  await expect(
    page.getByText('2 match(es) found.', { exact: true })
  ).toBeVisible();
  await page
    .getByLabel('Test text', { exact: true })
    .fill('private_sample #one');
  await expect(page.getByRole('checkbox')).not.toBeChecked();
  await expect(
    page.getByRole('heading', { name: /Authored sample explanation/ })
  ).toHaveCount(0);
  await expect(
    page.getByRole('heading', { name: 'Local match results' })
  ).toHaveCount(0);
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Show sample explanation' }).click();
  await expect(page.getByText(/No authored explanation matches/)).toBeVisible();
  await page.getByRole('button', { name: 'Test regex locally' }).click();
  await expect(
    page.getByText('1 match(es) found.', { exact: true })
  ).toBeVisible();
  await page.getByLabel('Regex pattern', { exact: true }).fill('[');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Test regex locally' }).click();
  await expect(
    page
      .locator('[role="alert"]')
      .filter({ hasText: /Invalid regular expression|Unterminated|invalid/i })
  ).toBeVisible();
  expect(uploads).toEqual([]);
  expect(requests.join('\n')).not.toContain('private_sample');
});

test('a catastrophic expression stays off-thread and recovers across engines', async ({
  page
}) => {
  await page.goto('/regex-assistant');
  await page.getByLabel('Regex pattern', { exact: true }).fill('(a+)+$');
  await page.getByLabel('Regex flags', { exact: true }).fill('');
  await page
    .getByLabel('Test text', { exact: true })
    .fill('a'.repeat(4000) + '!');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Test regex locally' }).click();
  expect(await page.evaluate(() => 1 + 1)).toBe(2);
  // Engines may bound backtracking internally and finish with no match before
  // our deadline. Both bounded completion and worker timeout are valid here.
  await expect(
    page.getByText(/Regex test timed out|^0 match\(es\) found\.$/)
  ).toBeVisible({ timeout: 10000 });
  await page.getByLabel('Regex pattern', { exact: true }).fill('^ok$');
  await page.getByLabel('Test text', { exact: true }).fill('ok');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Test regex locally' }).click();
  await expect(
    page.getByText('1 match(es) found.', { exact: true })
  ).toBeVisible();
});

test('a genuinely stuck worker times out without blocking the page and a fresh run succeeds', async ({
  page
}) => {
  const workerScript = '**/assets/regex.worker-*.js';
  await page.route(workerScript, (route) =>
    route.fulfill({
      contentType: 'application/javascript',
      body: 'self.onmessage = () => { while (true) {} };'
    })
  );
  await page.goto('/regex-assistant');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Test regex locally' }).click();
  expect(await page.evaluate(() => 1 + 1)).toBe(2);
  await expect(page.getByText(/Regex test timed out/)).toBeVisible({
    timeout: 10000
  });
  await expect(
    page.getByRole('button', { name: 'Cancel test' })
  ).toBeDisabled();
  await page.unroute(workerScript);
  await page.getByLabel('Regex pattern', { exact: true }).fill('^ok$');
  await page.getByLabel('Regex flags', { exact: true }).fill('');
  await page.getByLabel('Test text', { exact: true }).fill('ok');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Test regex locally' }).click();
  await expect(
    page.getByText('1 match(es) found.', { exact: true })
  ).toBeVisible();
});

test('cancel stops an active worker and an empty global match does not loop', async ({
  page
}) => {
  await page.goto('/regex-assistant');
  await page.getByLabel('Regex pattern', { exact: true }).fill('(a+)+$');
  await page
    .getByLabel('Test text', { exact: true })
    .fill('a'.repeat(4000) + '!');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Test regex locally' }).click();
  await page.getByRole('button', { name: 'Cancel test' }).click();
  await expect(page.getByRole('checkbox')).not.toBeChecked();
  await expect(page.getByText(/Testing in the local worker/)).toHaveCount(0);
  await page.getByLabel('Regex pattern', { exact: true }).fill('^|$');
  await page.getByLabel('Test text', { exact: true }).fill('abc');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Test regex locally' }).click();
  await expect(
    page.getByText('2 match(es) found.', { exact: true })
  ).toBeVisible();
  await expect(
    page.locator('li').filter({ hasText: '(empty match)' })
  ).toHaveCount(2);
});
